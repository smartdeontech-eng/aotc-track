// AOTC Track — action points PDF (A4, PCG letterhead). A shareable table of a
// meeting's action points with the assigned persons, target dates and status —
// for printing or posting alongside the WhatsApp summary.
const PDFDocument = require('pdfkit');
const path = require('path');
const fs = require('fs');

const CREST = path.join(__dirname, '..', 'public', 'img', 'logo.png');
const A4 = { width: 595.28, height: 841.89 };
const M = { top: 54, bottom: 54, left: 54, right: 54 };
const USABLE = A4.width - M.left - M.right;
// No. | Action point | Responsible | Target | Status  (sums to USABLE)
const COLS = [22, 233, 100, 62, USABLE - 22 - 233 - 100 - 62];
const HEADERS = ['#', 'Action point / decision', 'Responsible', 'Target', 'Status'];

function drawRow(doc, y, texts, opts = {}) {
  const pad = 4;
  const font = (opts.bold || opts.header) ? 'Times-Bold' : 'Times-Roman';
  doc.font(font).fontSize(9.5);
  const heights = texts.map((t, i) => doc.heightOfString(String(t == null ? '' : t), { width: COLS[i] - 2 * pad }));
  const rowH = Math.max(15, ...heights) + 2 * pad;
  if (opts.shade || opts.header) {
    doc.rect(M.left, y, USABLE, rowH).fill(opts.header ? '#1D3F94' : '#EEF2FA');
  }
  let x = M.left;
  texts.forEach((t, i) => {
    doc.rect(x, y, COLS[i], rowH).strokeColor('#C9CFDD').lineWidth(0.5).stroke();
    doc.fillColor(opts.header ? '#FFFFFF' : (opts.muted ? '#666' : '#000')).font(font).fontSize(9.5)
      .text(String(t == null ? '' : t), x + pad, y + pad, { width: COLS[i] - 2 * pad });
    x += COLS[i];
  });
  doc.fillColor('#000');
  return y + rowH;
}

function buildActionPointsPdf(data) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margins: M, bufferPages: true, info: { Title: `Action Points — ${data.entityName || ''}` } });
    const chunks = [];
    doc.on('data', c => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // ---- Letterhead ----
    doc.font('Times-Bold').fontSize(14).fillColor('#000').text('Presbyterian Church of Ghana', M.left, doc.y, { width: USABLE, align: 'center' });
    const crestW = 56, crestY = doc.y + 4;
    try { if (fs.existsSync(CREST)) doc.image(CREST, (A4.width - crestW) / 2, crestY, { fit: [crestW, 64] }); } catch (e) {}
    doc.y = crestY + 68;
    doc.font('Times-Bold').fontSize(11.5).text('Adabraka Official Town Congregation', M.left, doc.y, { width: USABLE, align: 'center' });
    doc.moveDown(0.5);
    doc.font('Times-Bold').fontSize(13).text(`ACTION POINTS — ${data.entityName || ''}`, { width: USABLE, align: 'center' });
    doc.font('Times-Roman').fontSize(10.5).fillColor('#333').text(`${data.meetingTitle || 'Meeting'}${data.dateStr ? ' · ' + data.dateStr : ''}`, { width: USABLE, align: 'center' });
    doc.moveDown(0.7);
    doc.fillColor('#000');

    // ---- Table ----
    const rows = data.rows || [];
    let y = doc.y;
    y = drawRow(doc, y, HEADERS, { header: true });
    if (!rows.length) {
      drawRow(doc, y, ['', 'No action points recorded.', '', '', ''], { muted: true });
    } else {
      rows.forEach((r, i) => {
        // page break
        if (y > A4.height - M.bottom - 40) { doc.addPage(); y = M.top; y = drawRow(doc, y, HEADERS, { header: true }); }
        y = drawRow(doc, y, [String(i + 1), r.text || '', r.responsible || 'Unassigned', r.target || '—', r.status || 'Open'], { shade: i % 2 === 1, muted: r.status === 'Done' });
      });
    }

    // ---- Footer ----
    doc.font('Times-Roman').fontSize(8.5).fillColor('#666')
      .text(`Generated by AOTC Track${data.generatedOn ? ' · ' + data.generatedOn : ''}. Please update the Secretary once your item is done.`, M.left, A4.height - M.bottom + 8, { width: USABLE, align: 'center' });

    doc.end();
  });
}

module.exports = { buildActionPointsPdf };
