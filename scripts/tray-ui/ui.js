const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const jwt = require('/home/claude/app/node_modules/jsonwebtoken');
const W = Number(process.env.W || 390);
let fail = 0, n = 0; const ok = (c, m) => { n++; console.log((c ? '  PASS ' : '  FAIL ') + m); if (!c) fail++; };
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' }).catch(() => chromium.launch());
  const ctx = await b.newContext({ viewport: { width: W, height: 800 }, hasTouch: W < 700, isMobile: W < 700 });
  await ctx.addCookies([{ name: 'token', value: jwt.sign({ id: 1, name: 'Clerk', email: 'c@t', role: 'admin', sv: 0 }, process.env.JWT_SECRET, { expiresIn: '2h' }), url: 'http://127.0.0.1:4555' }]);
  const pg = await ctx.newPage();
  const errors = []; pg.on('pageerror', e => errors.push(e.message));
  await pg.goto('http://127.0.0.1:4555/correspondence.html'); await pg.waitForSelector('#scanBtn');
  await pg.click('#scanBtn');
  ok(await pg.isVisible('#trayOverlay'), 'Scan a letter opens the tray');
  ok(/No pages yet/.test(await pg.textContent('#trayCount')) && await pg.isDisabled('#trayGo'), 'empty tray: Upload disabled');
  ok((await pg.getAttribute('#trayCamIn', 'capture')) === 'environment', 'Take a photo asks for the back camera');
  await pg.setInputFiles('#trayCamIn', 'big.jpg');
  await pg.waitForFunction(() => document.querySelectorAll('#trayPages .tp').length === 1);
  const kb = Number((await pg.textContent('#trayPages .tp figcaption')).match(/(\d+) KB/)[1]);
  ok(kb < 900 && kb > 20, `a 1,360 KB photo is shrunk before upload (${kb} KB)`);
  await pg.setInputFiles('#trayPickIn', ['small.png', 'letter.pdf']);
  await pg.waitForFunction(() => document.querySelectorAll('#trayPages .tp').length === 3);
  ok(/3 of 10 pages/.test(await pg.textContent('#trayCount')) && /Upload 3 pages as one letter/.test(await pg.textContent('#trayGo')), 'three pages, count and button say so');
  ok(await pg.$$eval('#trayPages .tp', els => els[2].querySelector('.pg-pdf') !== null), 'the PDF shows as a PDF tile');
  await pg.click('#trayPages .tp:nth-child(3) button[title="Earlier"]');
  ok(await pg.$$eval('#trayPages .tp', els => els[1].querySelector('.pg-pdf') !== null), '◀ moves the PDF to page 2');
  await pg.click('#trayPages .tp:nth-child(3) button[title="Remove"]');
  ok((await pg.$$('#trayPages .tp')).length === 2, '✕ removes a page');
  ok(await pg.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'no sideways scroll');
  await pg.screenshot({ path: `tray-${W}.png` });
  // the phone reloads the page behind the camera
  await pg.waitForTimeout(400);
  await pg.reload(); await pg.waitForSelector('#scanBtn');
  await pg.waitForFunction(() => document.getElementById('trayOverlay').style.display === 'flex', null, { timeout: 5000 }).catch(() => {});
  ok(await pg.isVisible('#trayOverlay') && (await pg.$$('#trayPages .tp')).length === 2, 'after a reload the two pages are put back');
  ok(await pg.$$eval('#trayPages .tp', els => els[1].querySelector('.pg-pdf') !== null), '…in the order they were left');
  await pg.click('#trayGo');
  await pg.waitForFunction(() => document.getElementById('trayOverlay').style.display === 'none', null, { timeout: 15000 });
  await pg.waitForSelector('.letter');
  const pages = await pg.$$eval('.letter:first-child .page-strip .pg', els => els.length);
  ok(pages === 2, `uploaded as ONE letter with 2 pages (${pages})`);
  const order = await pg.$$eval('.letter:first-child .page-strip .pg', els => els.map(e => !!e.querySelector('.pg-pdf')));
  ok(order.join() === 'false,true', 'the pages are stored in the tray order');
  await pg.reload(); await pg.waitForSelector('.letter'); await pg.waitForTimeout(500);
  ok(!(await pg.isVisible('#trayOverlay')), 'after upload the tray is not put back on reload');
  // + Add pages to that letter
  const before = await pg.$$eval('.letter:first-child .page-strip .pg', els => els.length);
  await pg.click('.letter:first-child button:has-text("+ Add pages")');
  ok(/Add pages to/.test(await pg.textContent('#trayTitle')), '+ Add pages opens the same tray, for that letter');
  await pg.setInputFiles('#trayPickIn', 'small.png');
  await pg.waitForFunction(() => /Add 1 page/.test(document.getElementById('trayGo').textContent));
  await pg.click('#trayGo');
  await pg.waitForFunction(() => document.getElementById('trayOverlay').style.display === 'none', null, { timeout: 15000 });
  await pg.waitForTimeout(300);
  const after = await pg.$$eval('.letter:first-child .page-strip .pg', els => els.length);
  ok(after === before + 1, `the letter gains the page (${before} → ${after})`);
  // the 10-page limit
  await pg.click('#scanBtn');
  await pg.setInputFiles('#trayPickIn', Array(11).fill('small.png'));
  await pg.waitForFunction(() => document.querySelectorAll('#trayPages .tp').length === 10, null, { timeout: 8000 }).catch(() => {});
  ok((await pg.$$('#trayPages .tp')).length === 10 && await pg.isDisabled('#trayCam'), 'at most 10 pages; the add buttons switch off at 10');
  pg.once('dialog', d => d.accept());
  await pg.click('#trayCancel');
  await pg.waitForTimeout(300);
  const confirmBtn = await pg.$('.app-dialog .btn-danger');
  if (confirmBtn) await confirmBtn.click();
  await pg.waitForTimeout(300);
  ok(!(await pg.isVisible('#trayOverlay')), 'Cancel (with pages) asks first, then puts them away');
  ok(!errors.length, 'no page errors' + (errors.length ? ': ' + errors.join(' | ') : ''));
  await b.close();
  console.log(`\n${n - fail}/${n} at ${W}px`); process.exit(fail ? 1 : 0);
})();
